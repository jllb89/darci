import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {writeFileSync,mkdtempSync} from 'node:fs';
import {createRequire} from 'node:module';
import {withPrivateNotificationWorker,assertEmptyNotificationBacklog} from './notification-rollout.mjs';
assert(process.argv.includes('--approved-private-notification-rollout'));
process.umask(0o077);
const aws=(...a)=>JSON.parse(execFileSync('aws',[...a,'--region','us-east-1','--output','json'],{encoding:'utf8',stdio:['ignore','pipe','pipe']})||'{}');
assert.equal(aws('sts','get-caller-identity').Account,'427057633951');
const stack=aws('cloudformation','describe-stacks','--stack-name','darci-production-runtime').Stacks[0];
assert.equal(stack.StackStatus,'UPDATE_COMPLETE');
const raw=aws('cloudformation','get-template','--stack-name',stack.StackName).TemplateBody;
const baseline=typeof raw==='string'?JSON.parse(raw):raw,template=withPrivateNotificationWorker(baseline);
const secret=JSON.parse(aws('secretsmanager','get-secret-value','--secret-id','/darci/production/app','--version-id',stack.Parameters.find(p=>p.ParameterKey==='SecretVersion').ParameterValue).SecretString);
assert.equal(secret.SUPABASE_URL,'https://jdrgluisxhgegdsesman.supabase.co');
const require=createRequire(import.meta.url),{createClient}=require('../../backend/node_modules/@supabase/supabase-js');
const db=createClient(secret.SUPABASE_URL,secret.SUPABASE_SERVICE_ROLE_KEY,{auth:{persistSession:false,autoRefreshToken:false}});
const result=await db.from('notification_jobs').select('id,status,channel,created_at',{count:'exact'}).in('status',['queued','scheduled','processing','failed','partially_sent']);
assert(!result.error,'Notification audit query failed');assert.equal(result.count,0,'Nonempty backlog');assertEmptyNotificationBacklog(result.data);
const dir=mkdtempSync('.recovery-private/production-notification-rollout-');
const report={at:new Date().toISOString(),pendingJobs:0,stage:'deploying',scope:'Private email/in-app worker; push and all sales remain disabled'};
writeFileSync(dir+'/baseline.json',JSON.stringify(baseline),{mode:0o600});
writeFileSync(dir+'/template.json',JSON.stringify(template),{mode:0o600});
const save=()=>writeFileSync(dir+'/report.json',JSON.stringify(report,null,2),{mode:0o600});save();
aws('cloudformation','update-stack','--stack-name',stack.StackName,'--template-body','file://'+dir+'/template.json','--parameters',JSON.stringify(stack.Parameters.map(p=>({ParameterKey:p.ParameterKey,UsePreviousValue:true}))),'--capabilities','CAPABILITY_NAMED_IAM');
console.log(JSON.stringify({evidence:dir,stage:report.stage}));
for(let i=0;i<60;i++){
  await new Promise(r=>setTimeout(r,15000));
  const state=aws('cloudformation','describe-stacks','--stack-name',stack.StackName).Stacks[0];
  if(state.StackStatus.endsWith('_IN_PROGRESS'))continue;
  assert.equal(state.StackStatus,'UPDATE_COMPLETE');assert.deepEqual(state.Parameters,stack.Parameters);
  const deployed=aws('cloudformation','get-template','--stack-name',stack.StackName).TemplateBody;
  assert.deepEqual(typeof deployed==='string'?JSON.parse(deployed):deployed,template);
  const service=aws('ecs','describe-services','--cluster','darci-production','--services','darci-production-worker').services[0];
  assert.equal(service.deployments.length,1);assert.equal(service.deployments[0].rolloutState,'COMPLETED');assert.equal(service.runningCount,service.desiredCount);
  Object.assign(report,{stage:'complete',completedAt:new Date().toISOString(),taskDefinition:service.taskDefinition,passed:true});save();
  console.log(JSON.stringify({...report,evidence:dir}));process.exit(0);
}
throw Error('Deployment exceeded bounded wait; inspect before retrying');
