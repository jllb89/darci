import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {mkdtempSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {buildSmsDeliveryTemplate} from './sms-delivery-stack.mjs';
const environment=process.argv.includes('--approved-production-provider-configuration')?'production':'staging';
assert(environment==='production'||process.argv.includes('--approved-staging-sms-tracking'));
const aws=(...args)=>JSON.parse(execFileSync('aws',[...args,'--region','us-east-1','--output','json'],{encoding:'utf8',stdio:['ignore','pipe','pipe']}) || '{}');
assert.equal(aws('sts','get-caller-identity').Account,'427057633951');
const dir=mkdtempSync(join(tmpdir(),'darci-sms-tracking-')), file=join(dir,'template.json');
writeFileSync(file,JSON.stringify(buildSmsDeliveryTemplate(environment)),{mode:0o600});
aws('cloudformation','validate-template','--template-body','file://'+file);
execFileSync('aws',['cloudformation','deploy','--region','us-east-1','--stack-name',`darci-${environment}-sms-delivery`,'--template-file',file,'--capabilities','CAPABILITY_IAM','--tags',`Environment=${environment}`,'CostCenter=darci-monitoring','--no-fail-on-empty-changeset'],{stdio:'inherit'});
console.log(JSON.stringify({stack:`darci-${environment}-sms-delivery`,configuration:`darci-${environment}-auth-sms`,note:'Requires API configuration-set parameter. No SMS sent.'}));
